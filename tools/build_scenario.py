HEAD_FILL = PatternFill("solid", fgColor="4F6BED")
GROUP_FILL = PatternFill("solid", fgColor="E8ECFD")
WRAP = Alignment(wrap_text=True, vertical="top")


def write_sheet(ws, headers, rows, widths):
    ws.append(headers)
    for cell in ws[1]:
        cell.font = Font(bold=True, color="FFFFFF")
        cell.fill = HEAD_FILL
        cell.alignment = Alignment(wrap_text=True, vertical="center")
    for row in rows:
        ws.append(list(row))
    for i, w in enumerate(widths):
        ws.column_dimensions[chr(65 + i)].width = w
    for row in ws.iter_rows(min_row=2):
        for cell in row:
            cell.alignment = WRAP
    ws.freeze_panes = "B2"


def build(path: Path):
    # уже заполненные настройки (ID чата, админы) при пересборке не теряем
    settings = dict(DEFAULT_SETTINGS)
    if path.exists():
        from openpyxl import load_workbook
        old = load_workbook(path, read_only=True)
        if "Настройки" in old.sheetnames:
            for row in old["Настройки"].iter_rows(min_row=2, values_only=True):
                if row and row[0] in settings and row[1] not in (None, ""):
                    settings[row[0]] = str(row[1])
        old.close()
    wb = Workbook()
    ws = wb.active
    ws.title = "Инструкция"
    ws.column_dimensions["A"].width = 120
    for line in INSTRUCTION.split("\n"):
        ws.append([line])
    ws["A1"].font = Font(bold=True, size=14)
    for row in ws.iter_rows():
        row[0].alignment = Alignment(wrap_text=True)

    ws = wb.create_sheet("Настройки")
    write_sheet(ws, ["Параметр (не менять)", "Значение", "Пояснение"],
                [(k, v, SETTINGS_HELP.get(k, "")) for k, v in settings.items()], [42, 60, 70])

    ws = wb.create_sheet("Шаги")
    write_sheet(ws, ["ID шага", "Тип", "Текст сообщения", "Название в заявке", "Следующий шаг", 'Кнопка "Назад"',
                     "Картинки (ссылки)", "Проверка ввода", 'Текст кнопки "Готово"', "Сразу сообщить менеджеру"],
                STEPS, [18, 12, 70, 22, 15, 10, 20, 12, 16, 12])
    starts = {i for i, _ in GROUPS}
    for i in starts:
        for cell in ws[i + 2]:
            cell.fill = GROUP_FILL
    types = DataValidation(type="list", formula1='"' + ",".join(STEP_TYPES) + '"', allow_blank=False)
    yes_no = DataValidation(type="list", formula1='"да,нет"', allow_blank=True)
    ws.add_data_validation(types)
    ws.add_data_validation(yes_no)
    types.add(f"B2:B{len(STEPS) + 200}")
    yes_no.add(f"F2:F{len(STEPS) + 200}")
    yes_no.add(f"J2:J{len(STEPS) + 200}")

    ws = wb.create_sheet("Кнопки")
    write_sheet(ws, ["ID шага", "Текст кнопки", "Переход", "Попросить ввести", "Снимает другие", "Ссылка",
                     "Цвет кнопки", "Иконка (ID эмодзи)"],
                OPTIONS, [18, 50, 18, 50, 10, 30, 12, 20])
    yes_no2 = DataValidation(type="list", formula1='"да,нет"', allow_blank=True)
    ws.add_data_validation(yes_no2)
    yes_no2.add(f"E2:E{len(OPTIONS) + 300}")
    colors = DataValidation(type="list", formula1='"зелёная,синяя,красная"', allow_blank=True)
    ws.add_data_validation(colors)
    colors.add(f"G2:G{len(OPTIONS) + 300}")
    prev = None
    for row in ws.iter_rows(min_row=2):
        if row[0].value != prev and prev is not None:
            for cell in row:
                cell.border = Border(top=Side(style="thin"))
        prev = row[0].value

    ws = wb.create_sheet("Маршруты")
    write_sheet(ws, ["Ветка", "Шаги по порядку (через запятую)", "Откуда начинается"], ROUTES, [18, 110, 40])

    wb.active = 2  # открывать на листе "Шаги"
    wb.save(path)


